import { mkdir, mkdtemp, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";

import { describe, expect, it } from "vitest";

import { suggestLeaveOuts } from "../src/generated-files.js";
import { snapshotRepository } from "../src/repository.js";

async function repository(files: Readonly<Record<string, string>>): Promise<string> {
  const root = await mkdtemp(join(tmpdir(), "arbitra-generated-"));
  for (const [path, content] of Object.entries(files)) {
    await mkdir(dirname(join(root, path)), { recursive: true });
    await writeFile(join(root, path), content);
  }
  return root;
}

describe("files to suggest leaving out", () => {
  it("names the generated, vendored and minified files a snapshot reads, each with its reason", async () => {
    // Observed on veritra (October 25, 2026): 20,331 of its lines were Drift, gen-l10n, an emoji table and Flutter's
    // plugin registrants, left out of the audit by hand.
    const root = await repository({
      "server/api.pb.go": "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage api\n",
      "mobile/lib/storage/db.g.dart": "// GENERATED CODE - DO NOT MODIFY BY HAND\n\npart of 'db.dart';\n",
      "mobile/lib/storage/db.dart": "part 'db.g.dart';\nclass Db {}\n",
      "mobile/l10n.yaml": "arb-dir: lib/l10n\ntemplate-arb-file: app_en.arb\noutput-localization-file: app_localizations.dart\n",
      "mobile/lib/l10n/app_localizations.dart": "import 'dart:async';\nabstract class AppLocalizations {}\n",
      "mobile/lib/l10n/app_localizations_en.dart": "import 'app_localizations.dart';\nclass AppLocalizationsEn {}\n",
      "mobile/lib/l10n/l10n.dart": "export 'app_localizations.dart';\n",
      "mobile/lib/features/emoji_data.dart": "// Generated by scripts/gen-emoji-data.py. Do not edit by hand.\nconst emoji = [];\n",
      "mobile/linux/flutter/generated_plugin_registrant.cc": "//\n//  Generated file. Do not edit.\n//\n\n#include \"generated_plugin_registrant.h\"\n",
      ".gitattributes": "*.ps1 text eol=crlf\nsrc/schema/*.ts linguist-generated=true\ndocs/** -linguist-generated\n",
      "src/schema/types.ts": "export type Id = string;\n",
      "src/app.ts": "// This file is not generated: edit it freely.\nexport const app = 1;\n",
      "server/vendor/modules.txt": "# github.com/x/y v1.0.0\n",
      "server/vendor/github.com/x/y/y.go": "package y\n",
      "web/bundle.js": `var a=${"1+".repeat(6_000)}1;\n`,
      "web/app.min.js": "var b=1;\n",
      "web/src/api/generated.ts": "export interface paths {}\n",
    });
    try {
      const suggestions = await suggestLeaveOuts(await snapshotRepository(root));
      expect(Object.fromEntries(suggestions.map(({ path, reason }) => [path, reason]))).toEqual({
        "server/api.pb.go": "its first lines say: // Code generated by protoc-gen-go. DO NOT EDIT.",
        "mobile/lib/storage/db.g.dart": "its first lines say: // GENERATED CODE - DO NOT MODIFY BY HAND",
        "mobile/lib/l10n/app_localizations.dart": "written by flutter gen-l10n, as mobile/l10n.yaml sets",
        "mobile/lib/l10n/app_localizations_en.dart": "written by flutter gen-l10n, as mobile/l10n.yaml sets",
        "mobile/lib/features/emoji_data.dart": "its first lines say: // Generated by scripts/gen-emoji-data.py. Do not edit by hand.",
        "mobile/linux/flutter/generated_plugin_registrant.cc": "its first lines say: //  Generated file. Do not edit.",
        "src/schema/types.ts": ".gitattributes marks it linguist-generated",
        "server/vendor/github.com/x/y/y.go": "vendored by Go modules (server/vendor/modules.txt)",
        "web/bundle.js": "a line of 12,008 characters: minified or bundled",
        "web/app.min.js": "named like minified code",
        "web/src/api/generated.ts": "named like generated code",
      });
      expect(suggestions.find(({ path }) => path === "mobile/lib/storage/db.g.dart")?.lines).toBe(4);
      // Largest first, so the biggest saving reads first.
      expect(suggestions.map(({ lines }) => lines)).toEqual([...suggestions.map(({ lines }) => lines)].sort((a, b) => b - a));
    } finally { await rm(root, { recursive: true, force: true }); }
  });

  it("suggests nothing in a project written by hand", async () => {
    const root = await repository({ "src/index.ts": "export const generated = 'not a marker';\n", "src/notes.py": "# do not edit the tests by hand\n" });
    try { expect(await suggestLeaveOuts(await snapshotRepository(root))).toEqual([]); }
    finally { await rm(root, { recursive: true, force: true }); }
  });
});
