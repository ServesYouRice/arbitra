import { lstat, readFile } from "node:fs/promises";
import { join, posix } from "node:path";

import type { RepositorySnapshot, SourceFile } from "./repository.js";

/**
 * A file the snapshot reads that is most likely not written by hand, and why: a suggestion for the scope's leave-out
 * paths, which the person accepts or not; nothing is left out by itself. Observed on veritra (October 25, 2026):
 * 20,331 of its 123,595 lines were Drift's database code, gen-l10n's localizations, a script's emoji table and
 * Flutter's plugin registrants, left out by hand. An audit of them reports defects in code nobody edits.
 */
export interface LeaveOutSuggestion { readonly path: string; readonly lines: number; readonly reason: string }

const HEADER_LINES = 12;
const MARKERS: readonly RegExp[] = [
  /^\/\/ Code generated .* DO NOT EDIT\.$/u, // Go's convention
  /GENERATED CODE - DO NOT MODIFY BY HAND/u, // Dart's build_runner
  /@generated\b/u, // protobuf, Relay, Thrift and others
  /<auto-generated[\s/>]/u, // .NET
  /\b(?:auto-?generated|generated (?:file|code|by\b))[^\n]*\bdo not (?:edit|modify)\b/iu, // Flutter, and scripts' own headers
];
const NAMES: readonly (readonly [RegExp, string])[] = [
  [/\.min\.(?:js|css)$/u, "named like minified code"],
  // rokbot's (October 24, 2026) OpenAPI client is `frontend/src/api/generated.ts`, 3,713 lines with no marker.
  [/\.(?:g|freezed|gr|mocks)\.dart$|\.pb\.go$|_pb2(?:_grpc)?\.pyi?$|\.pb\.(?:cc|h)$|[._]generated\.[a-z]+$|(?:^|\/)generated\.[a-z]+$|(?:^|\/)__generated__\/|\.Designer\.cs$/u, "named like generated code"],
];
const MINIFIED_LINE = 5_000;

export async function suggestLeaveOuts(snapshot: RepositorySnapshot): Promise<readonly LeaveOutSuggestion[]> {
  const attributes = await gitAttributes(snapshot.root);
  const localizations = await localizationOutputs(snapshot);
  const vendored = await goVendorDirectories(snapshot);
  const reasonFor = (file: SourceFile): string | null => {
    const marked = attributes.find(({ pattern }) => pattern.test(file.path));
    if (marked !== undefined) return `.gitattributes marks it ${marked.attribute}`;
    const localization = localizations.get(file.path);
    if (localization !== undefined) return `written by flutter gen-l10n, as ${localization} sets`;
    const header = file.lines.slice(0, HEADER_LINES).find((line) => MARKERS.some((marker) => marker.test(line.trim())));
    if (header !== undefined) return `its first lines say: ${header.trim().slice(0, 120)}`;
    const named = NAMES.find(([pattern]) => pattern.test(file.path));
    if (named !== undefined) return named[1];
    const vendor = vendored.find((directory) => file.path.startsWith(`${directory}/`));
    if (vendor !== undefined) return `vendored by Go modules (${vendor}/modules.txt)`;
    const longest = file.lines.reduce((most, line) => Math.max(most, line.length), 0);
    if (/\.(?:[cm]?js|css)$/u.test(file.path) && longest > MINIFIED_LINE) return `a line of ${longest.toLocaleString("en-US")} characters: minified or bundled`;
    return null;
  };
  return snapshot.files.flatMap((file) => { const reason = reasonFor(file); return reason === null ? [] : [{ path: file.path, lines: file.lines.length, reason }]; })
    .sort((a, b) => b.lines - a.lines || a.path.localeCompare(b.path));
}

/** A regular file of the repository, or null: a link is not followed out of it. */
async function readOwn(root: string, path: string): Promise<string | null> {
  try {
    const full = join(root, ...path.split("/"));
    return (await lstat(full)).isFile() ? await readFile(full, "utf8") : null;
  } catch { return null; }
}

/** The root `.gitattributes` patterns that set `linguist-generated` or `linguist-vendored`, the way GitHub reads them. */
async function gitAttributes(root: string): Promise<readonly { readonly pattern: RegExp; readonly attribute: string }[]> {
  const text = await readOwn(root, ".gitattributes");
  if (text === null) return [];
  return text.split(/\r?\n/u).flatMap((line) => {
    const [pattern, ...attributes] = line.trim().split(/\s+/u);
    if (pattern === undefined || pattern === "" || pattern.startsWith("#")) return [];
    const attribute = attributes.find((entry) => /^linguist-(?:generated|vendored)(?:=true)?$/u.test(entry));
    return attribute === undefined ? [] : [{ pattern: wildmatch(pattern), attribute: attribute.replace(/=true$/u, "") }];
  });
}

/** A `.gitattributes` pattern as a regular expression over repository-relative paths. */
function wildmatch(pattern: string): RegExp {
  const anchored = pattern.replace(/\/$/u, "").includes("/");
  const body = pattern.replace(/^\//u, "").replace(/\/$/u, "/**");
  let source = "";
  for (let index = 0; index < body.length; index += 1) {
    const rest = body.slice(index);
    if (rest.startsWith("**/")) { source += "(?:.*/)?"; index += 2; }
    else if (rest.startsWith("/**")) { source += "/.*"; index += 2; }
    else if (rest.startsWith("**")) { source += ".*"; index += 1; }
    else if (body[index] === "*") source += "[^/]*";
    else if (body[index] === "?") source += "[^/]";
    else source += (body[index] ?? "").replace(/[.+^${}()|[\]\\]/gu, "\\$&");
  }
  return new RegExp(`${anchored ? "^" : "(?:^|/)"}${source}(?:/.*)?$`, "u");
}

/**
 * The files gen-l10n writes for each Flutter package whose `l10n.yaml` the repository holds: the output localization
 * file and one per locale beside it, in `output-dir` (by default `arb-dir`, by default `lib/l10n`).
 */
async function localizationOutputs(snapshot: RepositorySnapshot): Promise<ReadonlyMap<string, string>> {
  const packages = new Set(snapshot.files.flatMap(({ path }) => { const at = path.startsWith("lib/") ? 0 : path.indexOf("/lib/"); return at < 0 ? [] : [path.slice(0, at)]; }));
  const outputs = new Map<string, string>();
  for (const directory of packages) {
    const settingsPath = directory === "" ? "l10n.yaml" : `${directory}/l10n.yaml`;
    const settings = await readOwn(snapshot.root, settingsPath);
    if (settings === null) continue;
    const value = (key: string) => new RegExp(`^${key}:\\s*['"]?([^'"#\\s]+)`, "mu").exec(settings)?.[1];
    const output = posix.join(directory, value("output-dir") ?? value("arb-dir") ?? "lib/l10n");
    const stem = (value("output-localization-file") ?? "app_localizations.dart").replace(/\.dart$/u, "");
    const written = new RegExp(`^${stem.replace(/[.+^${}()|[\]\\]/gu, "\\$&")}(?:_[A-Za-z]+(?:_[A-Za-z]+)*)?\\.dart$`, "u");
    for (const { path } of snapshot.files) if (posix.dirname(path) === output && written.test(posix.basename(path))) outputs.set(path, settingsPath);
  }
  return outputs;
}

/** Folders named `vendor` that hold Go's `modules.txt`, so their code is the modules' and not the project's. */
async function goVendorDirectories(snapshot: RepositorySnapshot): Promise<readonly string[]> {
  const candidates = new Set(snapshot.files.flatMap(({ path }) => { const match = /^(?:(.*)\/)?vendor\//u.exec(path); return match === null ? [] : [match[1] === undefined ? "vendor" : `${match[1]}/vendor`]; }));
  const found: string[] = [];
  for (const directory of candidates) if (await readOwn(snapshot.root, `${directory}/modules.txt`) !== null) found.push(directory);
  return found;
}
